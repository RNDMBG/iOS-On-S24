#!/usr/bin/env python3
"""Read a built e1s boot image and write the loader-screen values.

usage: qemu_bootinfo.py IMAGE OUT.h OUT.txt

The values come from the Samsung boot v4 header and the appended SWEETXNU
payload, so the QEMU screen shows this image's real payload size, segment
count, ADT size, entry and command line. The framebuffer values are the e1s
targets (0xFA200000, 1080x2340); the RAM window is the payload's fallback.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import struct  # noqa: E402

from verify_boot import check_boot, check_image  # noqa: E402


def strip_hold(cmdline):
    return re.sub(r"\s*e1s\.hold=\d+", "", cmdline)


def main():
    if len(sys.argv) != 4:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    image, header_path, text_path = sys.argv[1:]
    data = open(image, "rb").read()
    kernel, _os_version = check_boot(data)
    info = check_image(kernel)

    off = info["payload_offset"]
    payload = kernel[off:]
    adt_off, adt_size = struct.unpack_from("<QQ", payload, 32)
    ui_payload = adt_off + adt_size
    cmdline = strip_hold(info["cmdline"])

    values = {
        "BI_IMAGE_NAME": os.path.basename(image),
        "BI_IMAGE_BYTES": len(data),
        "BI_KERNEL_BYTES": len(kernel),
        "BI_PAYLOAD_BYTES": ui_payload,
        "BI_NSEGS": info["segments"],
        "BI_ADT_BYTES": info["adt_size"],
        "BI_VIRT_BASE": info["virt_base"],
        "BI_ENTRY": info["entry"],
        "BI_PHYS_BASE": info["phys_base"],
        "BI_MEM_SIZE": info["mem_size"],
        "BI_CMDLINE": cmdline,
    }

    with open(header_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* generated by qemu_bootinfo.py from %s */\n" %
                os.path.basename(image))
        for name, value in values.items():
            if name == "BI_IMAGE_NAME":
                f.write('#define %s "%s"\n' % (name, value))
            elif name == "BI_CMDLINE":
                f.write('#define %s "%s"\n' % (name, value.replace("\\", "\\\\")
                                                .replace('"', '\\"')))
            elif isinstance(value, str):
                f.write("#define %s %s\n" % (name, value))
            else:
                f.write("#define %s 0x%xULL\n" % (name, value))

    with open(text_path, "w", encoding="utf-8", newline="\n") as f:
        for name, value in values.items():
            if isinstance(value, str):
                f.write("%s=%s\n" % (name, value))
            else:
                f.write("%s=0x%x\n" % (name, value))
    print("qemu_bootinfo: %s: %u-byte kernel, %u-byte payload, %u segments, "
          "ADT %u" % (os.path.basename(image), len(kernel), ui_payload,
                      info["segments"], info["adt_size"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
